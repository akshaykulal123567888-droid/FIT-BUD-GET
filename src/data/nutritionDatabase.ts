const STOP_WORDS = new Set([
  'cooked', 'steamed', 'boiled', 'roasted', 'fried', 'grilled', 'fresh', 'raw',
  'sliced', 'chopped', 'diced', 'pieces', 'piece', 'small', 'medium', 'large',
  'cup', 'bowl', 'plate', 'serving', 'with', 'and', 'style', 'puree', 'gravy',
  'curry', 'dish', 'preparation', 'shredded', 'homemade', 'traditional', 'light'
]);

const GENERIC_MODIFIERS = new Set([
  'masala', 'curry', 'gravy', 'fry', 'sabzi', 'dish', 'tadka', 'roast', 'sauce',
  'spiced', 'plain', 'hot', 'style', 'puree', 'special', 'classic', 'homestyle'
]);

function escapeRegExp(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function wordBoundaryMatch(text: string, phrase: string): boolean {
  if (!text || !phrase) return false;
  const cleanT = text.toLowerCase().trim();
  const cleanP = phrase.toLowerCase().trim();
  if (cleanT === cleanP) return true;
  const re = new RegExp(`\\b${escapeRegExp(cleanP)}\\b`, 'i');
  return re.test(cleanT);
}

/**
 * Searches the verified nutrition database for the best matching food item.
 * Strict matching ensures we never fabricate database links for unrelated dishes.
 * If no confident, verified database entry exists, returns null.
 */
export function matchFoodInDatabase(rawName: string): NutritionReferenceItem | null {
  if (!rawName) return null;
  const cleanInput = rawName.toLowerCase().trim();

  // 1. Exact name or alternate name match
  for (const item of NUTRITION_DATABASE) {
    if (item.name.toLowerCase() === cleanInput) return item;
    for (const alt of item.alternateNames) {
      if (alt.toLowerCase() === cleanInput) return item;
    }
  }

  const isPreparedDishQuery = ['kadai', 'kadhai', 'curry', 'gravy', 'butter masala', 'makhani', 'bhurji', 'tikka', 'biryani', 'fried rice', 'sabzi', 'korma', 'rogan'].some((w) =>
    cleanInput.includes(w)
  );

  // 2. Strict whole-word phrase match prioritizing longest matching phrase
  let bestPhraseMatch: NutritionReferenceItem | null = null;
  let bestPhraseLen = 0;

  for (const item of NUTRITION_DATABASE) {
    // If user queried a prepared dish/curry, skip pure raw base ingredients
    if (isPreparedDishQuery && item.name.includes('(Raw')) {
      continue;
    }

    for (const alt of item.alternateNames) {
      const cleanAlt = alt.toLowerCase();
      if (cleanAlt.length >= 3 && !STOP_WORDS.has(cleanAlt) && !GENERIC_MODIFIERS.has(cleanAlt)) {
        if (wordBoundaryMatch(cleanInput, cleanAlt)) {
          if (cleanAlt.length > bestPhraseLen) {
            bestPhraseLen = cleanAlt.length;
            bestPhraseMatch = item;
          }
        }
      }
    }
  }

  if (bestPhraseMatch && bestPhraseLen >= 4) {
    return bestPhraseMatch;
  }

  // 3. Meaningful noun token match (excluding common preparation adjectives and generic modifiers)
  const inputTokens = cleanInput
    .replace(/[(),/\\-]/g, ' ')
    .split(/\s+/)
    .filter((t) => t.length > 2 && !STOP_WORDS.has(t));

  if (inputTokens.length === 0) return null;

  // Primary non-modifier tokens in query
  const primaryInputTokens = inputTokens.filter((t) => !GENERIC_MODIFIERS.has(t));

  let bestTokenMatch: NutritionReferenceItem | null = null;
  let highestScore = 0;

  for (const item of NUTRITION_DATABASE) {
    if (isPreparedDishQuery && item.name.includes('(Raw')) {
      continue;
    }

    const itemTokens = new Set([
      ...item.name.toLowerCase().replace(/[(),/\\-]/g, ' ').split(/\s+/).filter((t) => t.length > 2 && !STOP_WORDS.has(t)),
      ...item.alternateNames.flatMap((a) =>
        a.toLowerCase().replace(/[(),/\\-]/g, ' ').split(/\s+/).filter((t) => t.length > 2 && !STOP_WORDS.has(t))
      ),
    ]);

    // Check if at least one primary non-modifier token matches
    const hasPrimaryMatch = primaryInputTokens.length === 0 || primaryInputTokens.some((t) => itemTokens.has(t));
    if (!hasPrimaryMatch) {
      continue; // Never match purely on generic modifiers like "masala"
    }

    let matchCount = 0;
    for (const token of inputTokens) {
      if (itemTokens.has(token)) {
        matchCount++;
      }
    }

    // Require high overlap: at least half of meaningful input tokens match
    if (matchCount > 0 && matchCount >= Math.ceil(inputTokens.length * 0.5)) {
      if (matchCount > highestScore) {
        highestScore = matchCount;
        bestTokenMatch = item;
      }
    }
  }

  return bestTokenMatch;
}

/**
 * Rule 4 & 6:
 * Mathematical portion calculation from verified 100g reference amount:
 * nutrient for portion = (nutrient per 100g * portion weight in grams) / 100
 *
 * Runs Atwater diagnostic check ONLY (as a validation check).
 * CRITICAL RULE: NEVER modifies the real database values to match Atwater.
 */
export function calculateNutrientsForPortion(
  item: NutritionReferenceItem,
  portionGrams: number
) {
  const safeGrams = Math.max(1, Math.round(portionGrams));
  const factor = safeGrams / 100;

  // Strict mathematical scaling from verified 100g reference
  const calories = Math.round(item.caloriesPer100g * factor);
  const protein = Number((item.proteinPer100g * factor).toFixed(1));
  const carbs = Number((item.carbsPer100g * factor).toFixed(1));
  const fat = Number((item.fatPer100g * factor).toFixed(1));
  const fiber = Number((item.fiberPer100g * factor).toFixed(1));

  // Atwater validation check ONLY: (4P + 4C + 9F)
  const theoreticalAtwater = Math.round(protein * 4 + carbs * 4 + fat * 9);
  const atwaterDiff = Math.abs(calories - theoreticalAtwater);
  // Difference tolerance accounts for fiber deduction, rounding, organic acids
  const isAtwaterConsistent = atwaterDiff <= Math.max(25, Math.round(theoreticalAtwater * 0.18));

  // Approximate local grocery/preparation cost estimate based on portion weight
  const costPer100g = (item.costPerServing / (item.portionGrams || 100)) * 100;
  const estimatedCost = Math.round((costPer100g * safeGrams) / 100);

  return {
    portionGrams: safeGrams,
    calories,
    protein,
    carbs,
    fat,
    fiber,
    estimatedCost: Math.max(1, estimatedCost),
    source: item.source,
    isDatabaseVerified: true,
    isVariableDish: !!item.isVariableDish,
    variableNote: item.variableNote,
    referencePer100g: {
      calories: item.caloriesPer100g,
      protein: item.proteinPer100g,
      carbs: item.carbsPer100g,
      fat: item.fatPer100g,
      fiber: item.fiberPer100g,
    },
    costPer100g,
    isConsistent: isAtwaterConsistent,
    atwaterValidation: {
      isConsistent: isAtwaterConsistent,
      atwaterKcal: theoreticalAtwater,
      diffKcal: atwaterDiff,
    },
  };
}

/**
 * Rule 6: Atwater factor calculation check ONLY as an analytical validation check:
 * Calories from macros ≈ (Protein × 4) + (Carbohydrates × 4) + (Fat × 9)
 *
 * CRITICAL RULE: NEVER modify real database values just to match this equation.
 * Database calories differ due to fiber deduction, rounding, moisture, and analytical methodology.
 */
export function validateAndReconcileNutrients(
  calories: number,
  protein: number,
  carbs: number,
  fat: number,
  fiber: number = 0
) {
  const safeCalories = Math.max(0, Math.round(calories));
  const safeProtein = Math.max(0, Number(protein) || 0);
  const safeCarbs = Math.max(0, Number(carbs) || 0);
  const safeFat = Math.max(0, Number(fat) || 0);
  const safeFiber = Math.max(0, Number(fiber) || 0);

  const theoreticalAtwater = Math.round(safeProtein * 4 + safeCarbs * 4 + safeFat * 9);
  const diffKcal = Math.abs(safeCalories - theoreticalAtwater);

  // Acceptable tolerance: 25 kcal or 18% difference accounting for fiber, resistant starch, organic acids
  const isConsistent = diffKcal <= Math.max(25, Math.round(theoreticalAtwater * 0.18));

  return {
    isConsistent,
    theoreticalAtwater,
    diffKcal,
    reconciledCalories: safeCalories, // Do NOT modify database values
    correctionNote: !isConsistent
      ? `Calories (${safeCalories} kcal) differ by ${diffKcal} kcal from (4P+4C+9F = ${theoreticalAtwater} kcal) due to recipe ingredients or dietary fiber.`
      : undefined,
  };
}

export interface SanityCheckResult {
  isValid: boolean;
  warnings: string[];
}

/**
 * Rule 5: Sanity check before presenting result
 * Verifies biological realism for canonical food categories:
 * - Meat / Poultry / Fish (e.g. Roasted Chicken) must NOT have abnormal carbohydrates
 * - Plain boiled rice or grains must NOT have high fat
 * - Standard dosa or idli must NOT have unrealistic protein
 * - Pure oils and fats must be predominantly fat
 * - Calorie consistency check using (4P + 4C + 9F)
 */
export function runSanityCheck(
  foodName: string,
  category: string | undefined,
  portionGrams: number,
  calories: number,
  protein: number,
  carbs: number,
  fat: number,
  fiber: number = 0
): SanityCheckResult {
  const warnings: string[] = [];
  const safeGrams = Math.max(1, portionGrams);
  const factor = safeGrams / 100;

  // Normalized per 100g values
  const c100 = carbs / factor;
  const p100 = protein / factor;
  const f100 = fat / factor;

  const lower = foodName.toLowerCase();

  // 1. Meat / Poultry (e.g. roasted chicken): carbs should be negligible (< 6g/100g)
  const isPlainMeat =
    category === 'Meat & Fish' ||
    category === 'Eggs & Poultry' ||
    (['chicken', 'mutton', 'fish', 'prawn', 'meat', 'tandoori chicken', 'roasted chicken', 'roast chicken'].some((w) =>
      lower.includes(w)
    ) &&
      !lower.includes('curry') &&
      !lower.includes('biryani') &&
      !lower.includes('burger') &&
      !lower.includes('rice') &&
      !lower.includes('sandwich'));

  if (isPlainMeat && c100 > 8) {
    warnings.push(`Abnormal carbohydrates (${Math.round(carbs)}g) for meat/poultry item "${foodName}". Real poultry contains near-zero carbs.`);
  }

  // 2. Plain boiled grains / rice: fat should be low (< 4g/100g)
  const isPlainRice = ['steamed rice', 'white rice', 'boiled rice', 'plain rice', 'chawal'].some((w) => lower.includes(w));
  if (isPlainRice && f100 > 4) {
    warnings.push(`Abnormal fat (${Math.round(fat)}g) for plain boiled rice.`);
  }

  // 3. Plain Dosa / Idli: protein should be realistic (~3.5-4.5g/100g, never > 6.5g/100g)
  const isDosaOrIdli = ['dosa', 'idli', 'appam'].some((w) => lower.includes(w)) && !lower.includes('egg') && !lower.includes('chicken');
  if (isDosaOrIdli && p100 > 6.5) {
    warnings.push(`Abnormal protein (${Math.round(protein)}g) for dosa/idli. Standard fermented rice-dal batter yields ~3.5-4.5g protein per 100g.`);
  }

  // 4. Mixed Paneer Curries / Gravies: must not treat gravy as pure paneer
  const isPaneerCurry = ['paneer kadai', 'kadai paneer', 'paneer butter masala', 'makhani', 'matar paneer', 'shahi paneer'].some((w) => lower.includes(w));
  if (isPaneerCurry && p100 > 11.0) {
    warnings.push(`Abnormal protein (${Math.round(protein)}g) for paneer curry. Prepared paneer curry contains ~7-8g protein per 100g (a 250g serving contains ~18-20g protein, not 45-50g).`);
  }

  // 5. Plain Vegetables / Sabzis: vegetables do not contain large amounts of protein (< 5g/100g)
  const isVegetableSabzi = (category === 'Vegetables & Sabzis' || ['bhindi', 'aloo gobi', 'gobi', 'baingan', 'cabbage', 'beans', 'mix veg'].some((w) => lower.includes(w))) &&
    !lower.includes('paneer') && !lower.includes('chicken') && !lower.includes('meat') && !lower.includes('egg');
  if (isVegetableSabzi && p100 > 5.0) {
    warnings.push(`Abnormal protein (${Math.round(protein)}g) for vegetable sabzi. Vegetables do not contain large amounts of protein.`);
  }

  // 6. Pure Oils / Fats: mostly fat
  const isOilOrGhee = ['oil', 'ghee', 'butter'].some((w) => lower.includes(w)) && !lower.includes('chicken') && !lower.includes('paneer') && !lower.includes('dal');
  if (isOilOrGhee && (c100 > 5 || p100 > 5)) {
    warnings.push(`Abnormal carbs or protein for pure fat/oil item "${foodName}".`);
  }

  // 7. Atwater macro consistency
  const atwater = Math.round(protein * 4 + carbs * 4 + fat * 9);
  const diff = Math.abs(calories - atwater);
  if (diff > Math.max(30, Math.round(atwater * 0.22))) {
    warnings.push(`Calories (${calories} kcal) inconsistent with macronutrient calculation (${atwater} kcal).`);
  }

  return {
    isValid: warnings.length === 0,
    warnings,
  };
}
